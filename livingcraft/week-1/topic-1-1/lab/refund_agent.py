from dataclasses import dataclass
from decimal import Decimal, InvalidOperation
from typing import Optional


class AuthorizationError(Exception):
    """The principal is not permitted to perform the action."""


class BusinessRuleError(Exception):
    """The proposed action violates a business invariant."""


class ApprovalRequired(Exception):
    """The action needs trusted approval and must not execute yet."""


@dataclass(frozen=True)
class Principal:
    # READ THIS: these four fields answer different questions:
    # subject = who is calling; role = their job role; scopes = granted actions;
    # accessible_order_ids = which specific orders they may access.
    subject: str
    role: str
    scopes: frozenset[str]
    accessible_order_ids: frozenset[str]


@dataclass(frozen=True)
class Order:
    order_id: str
    amount_paid: Decimal


@dataclass(frozen=True)
class TrustedApproval:
    """Approval created by trusted application workflow, not by the agent/user."""
    approval_id: str
    order_id: str
    amount: Decimal
    approver: str


ORDERS = {
    "order-100": Order("order-100", Decimal("1000.00")),
}

# A testable stand-in for the resource-owning refund service.
EXECUTED_REFUNDS: list[dict[str, str]] = []


def reset_execution_log() -> None:
    """Clear the simulated execution log between tests or demonstrations."""
    EXECUTED_REFUNDS.clear()


def require_permission(principal: Principal, permission: str) -> None:
    """Enforce role and scope; a scope alone is not sufficient."""
    # READ THIS: both checks matter. The role does not replace the scope,
    # and the scope does not replace the role.
    if permission not in principal.scopes:
        raise AuthorizationError(f"Missing required scope: {permission}")

    if permission == "refund:issue" and principal.role != "refund_operator":
        raise AuthorizationError("Role is not allowed to issue refunds")


def require_resource_access(principal: Principal, order: Order) -> None:
    # READ THIS: even an authorized refund operator cannot act on every order.
    if order.order_id not in principal.accessible_order_ids:
        raise AuthorizationError("Principal cannot access this order")


def _money(value: Decimal | int | float | str) -> Decimal:
    try:
        amount = Decimal(str(value))
    except (InvalidOperation, ValueError, TypeError) as exc:
        raise BusinessRuleError("Refund amount must be a valid number") from exc
    if not amount.is_finite():
        raise BusinessRuleError("Refund amount must be finite")
    return amount.quantize(Decimal("0.01"))


def validate_refund(
    amount: Decimal | int | float | str,
    amount_paid: Decimal,
    approval: Optional[TrustedApproval] = None,
    *,
    order_id: str,
) -> Decimal:
    # READ THIS: the amount must be valid, positive, and no greater than paid.
    amount = _money(amount)
    if amount <= 0:
        raise BusinessRuleError("Refund amount must be greater than zero")
    if amount > amount_paid:
        raise BusinessRuleError("Refund cannot exceed the amount paid")
    # OPTIONAL EXPERIMENT: change ₹500 to ₹400 in a temporary copy, observe
    # the behavior, then restore ₹500. This is not a required edit.
    if amount > Decimal("500.00"):
        if approval is None:
            raise ApprovalRequired("Refunds above ₹500 require trusted approval")
        # Bind approval to this exact order and amount, not merely to a yes/no flag.
        if approval.order_id != order_id or approval.amount != amount:
            raise AuthorizationError("Approval does not match this order and amount")
        if not approval.approval_id or not approval.approver:
            raise AuthorizationError("Approval record is incomplete")
    return amount


def execute_refund(order_id: str, amount: Decimal, *, actor: str) -> dict[str, str]:
    """Simulated execution boundary. Production service must enforce invariants too."""
    # READ THIS: this is the simulated side effect. Tests check whether it ran.
    record = {
        "order_id": order_id,
        "amount": f"{amount:.2f}",
        "actor": actor,
        "status": "executed",
    }
    EXECUTED_REFUNDS.append(record)
    return record.copy()


def issue_refund(
    principal: Principal,
    order_id: str,
    amount: Decimal | int | float | str,
    *,
    trusted_approval: Optional[TrustedApproval] = None,
) -> dict[str, str]:
    """Authorize, validate, then execute. No execution occurs on a failed check."""
    # ACTION BOUNDARY — follow this order carefully.
    # CHECK 1: Fail closed if the order is unknown.
    order = ORDERS.get(order_id)
    if order is None:
        raise BusinessRuleError("Unknown order")

    # CHECK 2: Is the caller allowed to issue refunds?
    require_permission(principal, "refund:issue")

    # CHECK 3: Is this caller allowed to access THIS order?
    require_resource_access(principal, order)

    # CHECK 4: Does the amount follow business rules and approval policy?
    validated_amount = validate_refund(
        amount, order.amount_paid, trusted_approval, order_id=order_id
    )
    # CHECK 5: Only now may the simulated side effect occur.
    # READ THIS: this call stays after every authorization and validation check.
    return execute_refund(order_id, validated_amount, actor=principal.subject)


def demo_principals() -> tuple[Principal, Principal]:
    # BEFORE RUNNING: predict which requests pass and which are blocked.
    operator = Principal(
        subject="support-agent-17",
        role="refund_operator",
        scopes=frozenset({"refund:issue", "orders:read"}),
        accessible_order_ids=frozenset({"order-100"}),
    )
    read_only = Principal(
        subject="support-viewer-04",
        role="read_only_support",
        scopes=frozenset({"orders:read"}),
        accessible_order_ids=frozenset({"order-100"}),
    )
    return operator, read_only


if __name__ == "__main__":
    operator, read_only = demo_principals()
    examples = [
        ("Valid ₹300 refund", operator, "order-100", "300", None),
        ("Read-only caller", read_only, "order-100", "300", None),
        ("Refund exceeds amount paid", operator, "order-100", "1200", None),
        ("Approval missing", operator, "order-100", "700", None),
    ]
    for label, principal, order_id, amount, approval in examples:
        reset_execution_log()
        try:
            result = issue_refund(principal, order_id, amount, trusted_approval=approval)
            print(f"{label}: ALLOWED -> {result}")
        except (AuthorizationError, BusinessRuleError, ApprovalRequired) as exc:
            print(f"{label}: BLOCKED -> {exc}; executions={len(EXECUTED_REFUNDS)}")
